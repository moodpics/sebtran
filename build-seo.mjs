// Regenerates the crawlable film index inside index.html (between the SEO-INDEX markers)
// from films.js. Run after editing films.js:   node build-seo.mjs
import fs from "node:fs";
import vm from "node:vm";

const w = {};
vm.runInNewContext(fs.readFileSync("films.js", "utf8"), { window: w });
const esc = s => String(s ?? "").replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

const group = list => {
  const by = new Map();
  for (const f of list) (by.get(f.client) || by.set(f.client, []).get(f.client)).push(f);
  return [...by.entries()].map(([client, films]) =>
    `<li><strong>${esc(client)}</strong>: ` + films.map(f =>
      `${esc(f.title)} (${esc(f.category)}${f.director ? `, directed by ${esc(f.director)}` : ""}${f.production ? `, production ${esc(f.production)}` : ""})`
    ).join("; ") + `</li>`).join("\n      ");
};

const html = `<!-- SEO-INDEX:START (generated by build-seo.mjs — do not edit by hand) -->
  <section class="sr-only" id="film-index" aria-label="Film index">
    <h2>Seb Trân — director of photography in Paris</h2>
    <h2 lang="fr">Seb Trân — DOP et chef opérateur à Paris</h2>
    <p>Seb Trân (also written Seb Tran, Sébastien Trân) is a Paris-based director of photography, also called cinematographer or DoP (in French: chef opérateur, directeur de la photographie, chef op). He shoots beauty, fashion, fragrance and luxury commercials, music videos and short films, and also directs. Brands he has shot for include AMI Paris, Yves Saint Laurent, Lancôme, Clarins, L'Oréal Paris, Biotherm, Balmain, Cartier and Chaumet.</p>
    <p lang="fr">Seb Trân est DOP et chef opérateur (directeur de la photographie) à Paris, spécialisé dans la publicité beauté, mode et parfums, les clips et les courts métrages. Il a éclairé des films pour AMI Paris, Yves Saint Laurent, Lancôme, Clarins, L'Oréal Paris, Biotherm, Balmain, Cartier et Chaumet. Il est aussi réalisateur.</p>
    <h3>Cinematography — films shot by Seb Trân as director of photography, by brand</h3>
    <ul>
      ${group(w.FILMS.cinematography)}
    </ul>
    <h3>Direction — films directed by Seb Trân, by brand</h3>
    <ul>
      ${group(w.FILMS.direction)}
    </ul>
    <p>Contact and showreel links: Instagram @_sebtran_, Vimeo vimeo.com/user83221295.</p>
  </section>
  <!-- SEO-INDEX:END -->`;

let page = fs.readFileSync("index.html", "utf8");
const re = /<!-- SEO-INDEX:START[\s\S]*?<!-- SEO-INDEX:END -->/;
if (re.test(page)) page = page.replace(re, () => html);
else page = page.replace("</main>", () => `${html}\n  </main>`);
fs.writeFileSync("index.html", page);
console.log("SEO index updated:", w.FILMS.cinematography.length, "cinematography +", w.FILMS.direction.length, "direction films");
